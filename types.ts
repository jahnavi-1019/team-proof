export type ContributionDimension =
  | 'ARCHITECTURE_DECISION'
  | 'CODE_QUALITY_HYGIENE'
  | 'PEER_REVIEW_LEVERAGE'
  | 'INCIDENT_RESOLUTION';

export interface ContributionRecord {
  id: string;
  authorId: string;
  authorName: string;
  timestamp: string;
  dimension: ContributionDimension;
  title: string;
  evidenceUri: string; // e.g. PR #402, ADR #12, Incident Post-mortem #89
  impactSummary: string;
  peerEndorsements: string[]; // List of peer userIds
  isAutoGeneratedExcluded: boolean;
}

export interface AntiGamingCheck {
  commitSha?: string;
  filesChanged: string[];
  linesAdded: number;
  linesDeleted: number;
  isFlaggedAsVanityOrGenerated: boolean;
  reason?: string;
}

export interface TeamMemberProfile {
  userId: string;
  fullName: string;
  contributionsByDimension: Record<ContributionDimension, number>;
  totalVerifiedImpacts: number;
  records: ContributionRecord[];
}
