import { test } from 'node:test';
import assert from 'node:assert/strict';
import { AntiGamingFilter } from './anti-gaming.js';
import { ContributionLedger } from './contribution-ledger.js';

test('TeamProof AntiGaming: flags vanity line-bloat from package-lock.json', () => {
  const audit = AntiGamingFilter.auditContribution(['package-lock.json'], 14000, 200);
  assert.equal(audit.isFlaggedAsVanityOrGenerated, true);
  assert.ok(audit.reason?.includes('lockfile'));

  const legitimateAudit = AntiGamingFilter.auditContribution(['src/auth/jwt.ts'], 85, 20);
  assert.equal(legitimateAudit.isFlaggedAsVanityOrGenerated, false);
});

test('TeamProof Ledger: tracks non-code leverage (ADRs, reviews, and post-mortems)', () => {
  const ledger = new ContributionLedger();

  ledger.recordContribution({
    id: 'c1',
    authorId: 'dev-alex',
    authorName: 'Alex River',
    timestamp: '2026-10-10',
    dimension: 'ARCHITECTURE_DECISION',
    title: 'Authored ADR-014: Zero-Knowledge Client Sessions',
    evidenceUri: 'docs/adr/014-zk-sessions.md',
    impactSummary: 'Eliminated central Redis session bottlenecks, saving $4,200/mo.',
    peerEndorsements: ['dev-sarah', 'eng-lead-bob'],
    isAutoGeneratedExcluded: false
  });

  ledger.recordContribution({
    id: 'c2',
    authorId: 'dev-alex',
    authorName: 'Alex River',
    timestamp: '2026-10-12',
    dimension: 'PEER_REVIEW_LEVERAGE',
    title: 'Code Review PR #502: Caught SQL Injection Vulnerability',
    evidenceUri: 'github.com/org/repo/pull/502',
    impactSummary: 'Blocked critical security flaw before staging deployment.',
    peerEndorsements: ['dev-carlos'],
    isAutoGeneratedExcluded: false
  });

  const profile = ledger.getMemberProfile('dev-alex');
  assert.equal(profile.totalVerifiedImpacts, 2);
  assert.equal(profile.contributionsByDimension.ARCHITECTURE_DECISION, 1);
  assert.equal(profile.contributionsByDimension.PEER_REVIEW_LEVERAGE, 1);
  assert.equal(profile.contributionsByDimension.CODE_QUALITY_HYGIENE, 0);
});
